# Writes code/clod_ambiguous.h: the Unicode East Asian Ambiguous-width codepoints. A classic console
# window (conhost) sizes these by asking its font, so the same character can be one cell in the
# consoles behind clod's tabs and two in the window clod draws into. The client measures exactly
# these in its own console.
#
#   python tools/gen_ambiguous.py code/clod_ambiguous.h
import sys
import unicodedata

ranges = []
for cp in range(0xA0, 0x110000):
    if 0xD800 <= cp <= 0xDFFF or 0xE000 <= cp <= 0xF8FF or cp >= 0xF0000:  # surrogates, private use
        continue
    c = chr(cp)
    if unicodedata.east_asian_width(c) != 'A' or unicodedata.category(c) in ('Mn', 'Me', 'Cf', 'Cc'):
        continue
    if 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF:  # variation selectors
        continue
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

with open(sys.argv[1], 'w', newline='\n') as out:
    out.write('// Generated by tools/gen_ambiguous.py from Unicode %s. Do not edit.\n' % unicodedata.unidata_version)
    out.write('// East Asian Ambiguous-width codepoints (no private use, marks or selectors): a classic console\n')
    out.write('// window sizes these by its font, so the client measures them in its own console.\n')
    out.write('static const u32 AmbiguousWidth[][2] = {\n')
    for i in range(0, len(ranges), 6):
        out.write('    ' + ' '.join('{0x%X, 0x%X},' % (a, b) for a, b in ranges[i:i + 6]) + '\n')
    out.write('};\n')
print(len(ranges), 'ranges,', sum(b - a + 1 for a, b in ranges), 'codepoints')
