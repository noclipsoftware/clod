# Turns a `widthprobe <file> --table` dump (system conhost widths) into code/clod_widths.h.
# ConPTY lays out child output with these widths, so clod's emulator must use exactly the same.
#
#   python tools/gen_widths.py build/table_conhost.txt code/clod_widths.h
import sys

widths = {}
for line in open(sys.argv[1]):
    cp, w = line.split()
    widths[int(cp, 16)] = int(w)

ranges = []
for cp in sorted(widths):
    if widths[cp] != 2:
        continue
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

# Beyond the probed planes: CJK extension planes are wide everywhere.
ranges += [[0x20000, 0x2FFFD], [0x30000, 0x3FFFD]]

with open(sys.argv[2], 'w', newline='\n') as out:
    out.write('// Generated by tools/gen_widths.py from a widthprobe dump of the system conhost. Do not edit.\n')
    out.write('// Codepoint ranges conhost (and so ConPTY) draws two cells wide; everything else is one cell.\n')
    out.write('static const u32 ConhostWide[][2] = {\n')
    for i in range(0, len(ranges), 6):
        out.write('    ' + ' '.join('{0x%X, 0x%X},' % (a, b) for a, b in ranges[i:i + 6]) + '\n')
    out.write('};\n')
print(len(ranges), 'ranges')
